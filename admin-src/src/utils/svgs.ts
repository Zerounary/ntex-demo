export const write = (draw, svg, opt = {}) => {
  opt = {
    cols: 20,
    rows: 10,
    scale: 0.25,
    fontColor: '#f3f3f3',
    ...opt,
  };
  let { cols, rows, scale, fontColor } = opt;
  let children = [];
  for (let i = 1; i <= cols; i++) {
    for (let j = 1; j <= rows; j++) {
      draw.svg(svg.value);
      children.push({
        main: draw.last(),
        i,
        j,
      });
    }
  }

  for (let node of children) {
    const { main, i, j } = node;

    main.fill(fontColor);

    main
      ?.cx(0)
      .cy(0)
      .transform({
        translateX: svg.width * scale * i,
        translateY: svg.height * scale * j,
        scale,
      });
  }
};

